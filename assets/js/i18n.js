function detectClientLanguage() {
  const navLangs = (typeof navigator !== 'undefined' && navigator.languages && navigator.languages.length) 
    ? navigator.languages 
    : [typeof navigator !== 'undefined' ? (navigator.language || navigator.userLanguage || '') : ''];

  for (let raw of navLangs) {
    if (!raw) continue;
    const l = raw.toLowerCase().trim();
    if (l === 'zh-tw' || l.startsWith('zh-hant-tw')) return 'zh-tw';
    if (l === 'zh-hk' || l === 'zh-mo' || l.includes('hant')) return 'zh-hk';
    if (l === 'zh' || l === 'zh-cn' || l === 'zh-sg' || l.startsWith('zh-hans') || l.startsWith('zh')) return 'zh';
    if (l.startsWith('ja')) return 'ja';
    if (l.startsWith('ko')) return 'ko';
    if (l.startsWith('vi')) return 'vi';
    if (l.startsWith('ru') || l.startsWith('uk') || l.startsWith('be') || l.startsWith('kk')) return 'ru';
    if (l.startsWith('es')) return 'es';
    if (l.startsWith('en')) return 'en';
  }
  return 'zh';
}

function detectPageLanguage() {
  if (typeof document !== 'undefined' && document.documentElement) {
    const docLang = document.documentElement.getAttribute('data-lang');
    if (docLang && translations[docLang]) return docLang;
  }
  if (typeof window !== 'undefined' && window.location) {
    const p = window.location.pathname.toLowerCase();
    const known = ['zh-tw', 'zh-hk', 'zh', 'en', 'ja', 'ko', 'vi', 'ru', 'es'];
    for (const l of known) {
      if (p.includes('/' + l + '/') || p.endsWith('/' + l) || p.endsWith('/' + l + '.html') || p.includes('\\' + l + '\\')) {
        return l;
      }
    }
  }
  return (typeof localStorage !== 'undefined' && localStorage.getItem('hermes_lang')) || detectClientLanguage();
}

let currentLang = detectPageLanguage();

function navigateToLanguage(newLang) {
  if (!translations[newLang]) return;
  if (typeof localStorage !== 'undefined') {
    localStorage.setItem('hermes_lang', newLang);
    localStorage.setItem('hermes_lang_manual', 'true');
  }

  if (typeof window === 'undefined' || !window.location) {
    setLanguage(newLang, true);
    return;
  }

  const currentPath = window.location.pathname;
  const isFileProto = window.location.protocol === 'file:';
  const currentHash = window.location.hash || '';
  const knownLangs = ['zh-tw', 'zh-hk', 'zh', 'en', 'ja', 'ko', 'vi', 'ru', 'es'];

  const currentSubLang = knownLangs.find(l => 
    currentPath.includes('/' + l + '/') || currentPath.endsWith('/' + l) || currentPath.includes('\\' + l + '\\')
  );

  if (currentSubLang === newLang) {
    setLanguage(newLang, true);
    return;
  }

  let targetUrl = '';
  if (isFileProto) {
    targetUrl = currentSubLang ? `../${newLang}/index.html${currentHash}` : `./${newLang}/index.html${currentHash}`;
  } else {
    targetUrl = currentSubLang ? `../${newLang}/${currentHash}` : `./${newLang}/${currentHash}`;
  }

  window.location.href = targetUrl;
}

function setLanguage(lang, isManual = false) {
  if (!translations[lang]) lang = 'zh';
  currentLang = lang;
  if (typeof localStorage !== 'undefined') {
    localStorage.setItem('hermes_lang', lang);
    if (isManual) {
      localStorage.setItem('hermes_lang_manual', 'true');
    }
  }

  // Synchronize document language attributes and typography mode classes
  if (typeof document !== 'undefined' && document.documentElement) {
    document.documentElement.lang = lang;
    document.documentElement.setAttribute('data-lang', lang);
    if (lang.startsWith('zh')) {
      document.documentElement.classList.add('lang-zh');
      document.documentElement.classList.remove('lang-non-zh');
    } else {
      document.documentElement.classList.remove('lang-zh');
      document.documentElement.classList.add('lang-non-zh');
    }
  }

  if (typeof document !== 'undefined') {
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (translations[lang] && translations[lang][key]) {
        el.textContent = translations[lang][key];
      }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (translations[lang] && translations[lang][key]) {
        el.setAttribute('placeholder', translations[lang][key]);
      }
    });

    const select = document.getElementById('lang-select') || document.getElementById('language-select');
    if (select) {
      select.value = lang;
    }

    if (translations[lang] && translations[lang].site_title) {
      document.title = translations[lang].site_title;
    }
  }

  // Notify dynamic widgets (radar probe nodes, pricing calculator)
  if (typeof window !== 'undefined') {
    window.dispatchEvent(new CustomEvent('hermesLanguageChanged', { detail: { lang } }));
  }
}

window.setLanguage = setLanguage;
window.navigateToLanguage = navigateToLanguage;

if (typeof document !== 'undefined') {
  document.addEventListener('DOMContentLoaded', () => {
    const select = document.getElementById('lang-select') || document.getElementById('language-select');
    if (select) {
      select.value = currentLang;
      select.addEventListener('change', (e) => {
        navigateToLanguage(e.target.value);
      });
    }
    setLanguage(currentLang, false);

    // Real-time client browser language change listener (only triggers if on root without subfolder)
    if (typeof window !== 'undefined') {
      window.addEventListener('languagechange', () => {
        const hasManualOverride = localStorage.getItem('hermes_lang_manual') === 'true';
        const currentPath = window.location.pathname;
        const knownLangs = ['zh-tw', 'zh-hk', 'zh', 'en', 'ja', 'ko', 'vi', 'ru', 'es'];
        const hasSubfolder = knownLangs.some(l => currentPath.includes('/' + l + '/') || currentPath.endsWith('/' + l));
        if (!hasManualOverride && !hasSubfolder) {
          const detected = detectClientLanguage();
          navigateToLanguage(detected);
        }
      });
    }
  });
}
